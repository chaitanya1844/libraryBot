#!/usr/bin/env python3
"""Reads a URDF/XML document on stdin and writes a single-line version with
XML comments and the <?xml ... ?> declaration removed, then prints it on
stdout.

gazebo_ros2_control re-parses the robot_description parameter through a
YAML-backed "--param key:=<value>" parameter-override parser
(rcl_yaml_param_parser). xacro's autogenerated ASCII-art comment header
(containing "|", "====", and a leading "<?xml ... ?>") trips that parser
with "Couldn't parse parameter override rule". Both the comments and the
XML declaration are optional/cosmetic, so stripping them (and collapsing
newlines) works around the bug without changing the robot model.
"""
import re
import sys


def main() -> None:
    text = sys.stdin.read()
    text = re.sub(r'<\?xml.*?\?>', '', text, flags=re.S)
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    sys.stdout.write(' '.join(text.split()))


if __name__ == '__main__':
    main()
